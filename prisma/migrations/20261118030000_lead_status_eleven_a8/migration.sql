-- A8: Replace LeadStatus with the client’s 11 Current Status values.
-- Old → new mapping:
--   NEW_LEAD              → NEW_PROSPECT
--   ATTEMPTING_CONTACT    → NO_ANSWER
--   FOLLOW_UP_NEEDED      → CALLBACK_REQUIRED
--   APPOINTMENT_SCHEDULED → ZOOM_SCHEDULED
--   QUALIFIED             → INTERESTED
--   PROPOSAL_SENT         → PROPOSAL_SENT
--   CLIENT_WON            → CLIENT_ACQUIRED
--   NOT_INTERESTED        → NOT_INTERESTED
--   NOT_QUALIFIED         → NOT_QUALIFIED
--   DO_NOT_CONTACT        → NOT_INTERESTED

ALTER TYPE "LeadStatus" RENAME TO "LeadStatus_old";

CREATE TYPE "LeadStatus" AS ENUM (
  'NEW_PROSPECT',
  'NO_ANSWER',
  'GATEKEEPER_REACHED',
  'DECISION_MAKER_REACHED',
  'CALLBACK_REQUIRED',
  'INTERESTED',
  'ZOOM_SCHEDULED',
  'PROPOSAL_SENT',
  'CLIENT_ACQUIRED',
  'NOT_INTERESTED',
  'NOT_QUALIFIED'
);

ALTER TABLE "leads"
  ALTER COLUMN "status" DROP DEFAULT,
  ALTER COLUMN "status" TYPE "LeadStatus"
  USING (
    CASE "status"::text
      WHEN 'NEW_LEAD' THEN 'NEW_PROSPECT'::"LeadStatus"
      WHEN 'ATTEMPTING_CONTACT' THEN 'NO_ANSWER'::"LeadStatus"
      WHEN 'FOLLOW_UP_NEEDED' THEN 'CALLBACK_REQUIRED'::"LeadStatus"
      WHEN 'APPOINTMENT_SCHEDULED' THEN 'ZOOM_SCHEDULED'::"LeadStatus"
      WHEN 'QUALIFIED' THEN 'INTERESTED'::"LeadStatus"
      WHEN 'PROPOSAL_SENT' THEN 'PROPOSAL_SENT'::"LeadStatus"
      WHEN 'CLIENT_WON' THEN 'CLIENT_ACQUIRED'::"LeadStatus"
      WHEN 'NOT_INTERESTED' THEN 'NOT_INTERESTED'::"LeadStatus"
      WHEN 'NOT_QUALIFIED' THEN 'NOT_QUALIFIED'::"LeadStatus"
      WHEN 'DO_NOT_CONTACT' THEN 'NOT_INTERESTED'::"LeadStatus"
      ELSE 'NEW_PROSPECT'::"LeadStatus"
    END
  );

ALTER TABLE "leads"
  ALTER COLUMN "status" SET DEFAULT 'NEW_PROSPECT'::"LeadStatus";

DROP TYPE "LeadStatus_old";
